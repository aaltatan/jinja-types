"""Write `docs/<namespace>.md` for every namespace, `docs/index.md` and the README reference.

Run with `uv run python scripts/gen_docs.py` on Python 3.12 (newer versions add members such as
`path.full_match`). `tests/test_docs.py` checks that the committed pages are up to date.
"""

from pathlib import Path

from jinja_types import Catalog, CatalogEntry, Registry
from jinja_types.core.catalog import short_repr

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
README = ROOT / "README.md"
HEADER = "<!-- Generated by scripts/gen_docs.py from the catalog. Do not edit. -->\n\n"
START = "<!-- reference:start (generated by scripts/gen_docs.py, do not edit) -->"
END = "<!-- reference:end -->"


def pages(catalog: Catalog) -> dict[str, str]:
    """Return `{file name: Markdown}` for every namespace page and the index."""

    result = {
        f"{namespace}.md": HEADER + catalog.select(namespace=namespace).to_markdown()
        for namespace in catalog.namespaces()
    }

    links = [
        f"- [`{namespace}`]({namespace}.md): {len(catalog.select(namespace=namespace))} members"
        for namespace in catalog.namespaces()
    ]

    result["index.md"] = HEADER + "\n".join(["# jinja-types reference", "", *links, ""])

    return result


def cell(text: str) -> str:
    """`text` as a code span that is safe inside a Markdown table cell."""

    if not text.strip():
        return f"*empty* (`{text!r}`)"

    return f"`` {text.replace('|', '\\|')} ``"


def call(entry: CatalogEntry) -> str:
    """`str.zfill(width)`: the member with its parameter names, without the piped value."""

    prefixes = {"var_positional": "*", "var_keyword": "**"}
    params = [prefixes.get(param.kind, "") + param.name for param in entry.params]

    if params or ("global" in entry.kinds and not entry.constant):
        return f"{entry.name}({', '.join(params)})"

    return entry.name


def reference(catalog: Catalog) -> str:
    """Return the README reference: one table per namespace, one row per example."""

    namespaces = catalog.namespaces()
    lines = [
        START,
        "",
        "## Reference",
        "",
        f"Every member ({len(catalog)}), with every example. Generated from the catalog.",
        "",
        " · ".join(f"[`{namespace}`](#{namespace})" for namespace in namespaces),
        "",
    ]

    for namespace in namespaces:
        lines += [
            f"### {namespace}",
            "",
            "| Member | Kinds | Description | Example | Result |",
            "|---|---|---|---|---|",
        ]

        for entry in catalog.select(namespace=namespace):
            description = entry.doc.split("\n")[0].replace("|", "\\|")

            for i, (template, context, output) in enumerate(entry.examples):
                given = ", ".join(f"{key} = {short_repr(value)}" for key, value in context.items())
                example = cell(template) + (f"<br>with {cell(given)}" if given else "")
                first = i == 0

                lines.append(
                    f"| {f'`{call(entry)}`' if first else ''} "
                    f"| {', '.join(entry.kinds) if first else ''} "
                    f"| {description if first else ''} | {example} | {cell(output)} |"
                )

        lines.append("")

    return "\n".join([*lines, END])


def readme(text: str, catalog: Catalog) -> str:
    """Return the README `text` with its reference section replaced."""

    head, rest = text.split(START, 1)

    return head + reference(catalog) + rest.split(END, 1)[1]


def main() -> None:
    DOCS.mkdir(exist_ok=True)

    catalog = Registry.default().catalog()

    for name, text in pages(catalog).items():
        (DOCS / name).write_text(text, encoding="utf-8", newline="\n")

    README.write_text(readme(README.read_text(encoding="utf-8"), catalog), encoding="utf-8")


if __name__ == "__main__":
    main()
